#!/usr/bin/env node
// =============================================================================
// Generates lib/analytics/timezone-countries.ts — IANA time zone → ISO country.
// =============================================================================
// Web analytics falls back to the visitor's device time zone for "which country
// is this visit from" when no CDN geo header is present (the site is served
// straight from Hetzner, so there usually isn't one). The OS sets the zone from
// the device's real location, so it's accurate to country level — and, unlike
// IP lookups, it isn't fooled by VPNs or sent to a third party.
//
// Source: the system tz database (zone.tab for zone → country, the link lines
// in tzdata.zi for legacy aliases such as Asia/Calcutta that some browsers
// still report). Re-run after a tzdata update:
//
//   node scripts/gen-timezone-countries.js
// =============================================================================

const fs = require('fs');
const path = require('path');

const ZONEINFO = process.env.ZONEINFO || '/usr/share/zoneinfo';
const OUT = path.join(__dirname, '..', 'lib', 'analytics', 'timezone-countries.ts');

const map = new Map();
for (const line of fs.readFileSync(path.join(ZONEINFO, 'zone.tab'), 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [cc, , zone] = line.split('\t');
  map.set(zone, cc);
}

// Aliases point at a canonical zone; they share its country, except a few
// microstates whose own name is only kept as a link.
const OWN_COUNTRY = { 'Europe/Vatican': 'VA', 'Europe/San_Marino': 'SM' };
for (const line of fs.readFileSync(path.join(ZONEINFO, 'tzdata.zi'), 'utf8').split('\n')) {
  if (!line.startsWith('L ')) continue;
  const [, target, alias] = line.split(' ');
  if (map.has(alias)) continue;
  const cc = OWN_COUNTRY[alias] || map.get(target);
  if (cc) map.set(alias, cc);
}

const entries = [...map.entries()].sort(([a], [b]) => a.localeCompare(b));
const body = entries.map(([zone, cc]) => `  '${zone}': '${cc}',`).join('\n');

fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-timezone-countries.js — do not edit by hand.
// IANA time zone (incl. legacy aliases) → ISO-3166 alpha-2 country.
// Server-only: used by the analytics collector, never shipped to the browser.

export const TIMEZONE_COUNTRY: Readonly<Record<string, string>> = {
${body}
};
`
);
console.log(`Wrote ${entries.length} zones to ${path.relative(process.cwd(), OUT)}`);
